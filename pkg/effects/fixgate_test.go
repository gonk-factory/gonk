// The boundary of each cap is INCLUSIVE: exactly at the cap passes.
func TestFixCapsAreInclusive(t *testing.T) {
	env := goodEnvelope(t)
	cases := []struct {
		name  string
		batch Batch
		base  func(b BaseBlobs)
	}{
		{"three files", fixWith(editEffect("pkg/example/a.go", "A = 1", "A = 2"), editEffect("pkg/example/b.go", "B = 1", "B = 2"),
			editEffect("pkg/example/c.go", "C = 1", "C = 2")), nil},
		{"forty changed lines", fixWith(editEffect("pkg/example/sum.go", "\treturn a - b\n", numbered(39, "\t_ = %d"))), nil},
		{"exactly 16 KiB of new text", fixWith(editEffect("pkg/example/sum.go", "a - b", strings.Repeat("x", 16<<10))), nil},
		{"a base file of exactly 256 KiB whose result is no larger", fixWith(editEffect("pkg/example/big.go", "Big = 1", "Big = 2")),
			func(b BaseBlobs) { b["pkg/example/big.go"] = b["pkg/example/big.go"][:256<<10] }},
	}
	for _, tc := range cases {
		base := goodBase()
		if tc.base != nil {
			tc.base(base)
		}
		if v := FixViolations(tc.batch, env, base, fixSecrets()); len(v) != 0 {
			t.Errorf("%s: violations %v, want none", tc.name, codes(v))
		}
	}
	// A result that GROWS past the file cap is refused although the base fits.
	base := goodBase()
	base["pkg/example/big.go"] = base["pkg/example/big.go"][:256<<10]
	v := FixViolations(fixWith(editEffect("pkg/example/big.go", "Big = 1", "Big = 1000")), env, base, fixSecrets())
	if !reflect.DeepEqual(codes(v), []string{"SC-SIZE(max_file_bytes)"}) {
		t.Errorf("a result over the file cap: violations %v", codes(v))
	}
	// And a BASE over the cap is refused although the result would fit: a file
	// that large is not one a fix session edits, whichever way it is going.
	base = goodBase()
	const marker = "// a unique marker line, removed by the edit\n"
	base["pkg/example/big.go"] = append(append([]byte{}, base["pkg/example/big.go"][:256<<10]...), marker...)
	v = FixViolations(fixWith(editEffect("pkg/example/big.go", marker, "")), env, base, fixSecrets())
	if !reflect.DeepEqual(codes(v), []string{"SC-SIZE(max_file_bytes)"}) {
		t.Errorf("a base over the file cap whose result fits: violations %v", codes(v))
	}
}

// The ci lift: a `configuration` dispatch may edit a pipeline definition, and
// a pipeline-included file, and nothing else.
func TestFixGateWithTheCILift(t *testing.T) {
	env := ciEnvelope(t)
	env.Base = scope.BaseFacts{CILocalIncludes: []string{"ci/build.yml"}}
	for _, b := range []Batch{
		fixWith(editEffect(".gitlab-ci.yml", "go test ./...", "go test -race ./...")),
		fixWith(editEffect("ci/build.yml", "go build ./...", "go build -v ./...")),
	} {
		plan, err := PlanFix(b, env, goodBase(), fixSecrets())
		if err != nil {
			t.Errorf("ci lift: %s refused: %v", b.Effects[0].Path, err)
			continue
		}
		if got := plan.Facts.Classes(); !reflect.DeepEqual(got, []scope.Class{scope.ClassCI}) {
			t.Errorf("ci lift: %s classes = %v", b.Effects[0].Path, got)
		}
	}
	// The same lift does not make source writable: the configuration row has no
	// ordinary class.
	v := FixViolations(goodFix(), env, goodBase(), fixSecrets())
	if !reflect.DeepEqual(codes(v), []string{"SC-CLASS(source)"}) {
		t.Errorf("source under the configuration envelope: %v", codes(v))
	}
}

// The phase functions refuse what PlanFix refuses, so APPLY may call them
// early (before fetching blobs) without a second definition of the rules.
