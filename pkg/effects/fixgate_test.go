// Near misses are not secrets: the patterns are the high-confidence ones only,
// or every source edit mentioning a token variable would be refused.
func TestSecretPatternsDoNotOverReach(t *testing.T) {
	for _, line := range []string{
		"token := os.Getenv(\"TOKEN\")",
		"password = input()",
		"// see glpat- prefix docs",
		"gl" + "pat-short",
		"AK" + "IA" + "TOOSHORT",
		"xAK" + "IA" + strings.Repeat("Q", 16) + "x",
		"-----BEGIN " + "CERTIFICATE-----",
		"-----BEGIN PUBLIC KEY-----",
	} {
		if kind, ok := FindSecret(line, fixSecrets()); ok {
			t.Errorf("FindSecret(%q) = %q, want nothing", line, kind)
		}
	}
	for line, want := range map[string]string{
		"x " + fakeGitLabTok + " y":                 "gitlab_token",
		fakeAWSKey:                                  "aws_access_key",
		fakePEMHeader:                               "private_key",
		"-----BEGIN " + "PRIVATE KEY-----":          "private_key",
		"-----BEGIN " + "OPENSSH PRIVATE KEY-----":  "private_key",
		"prefix" + fakeSessionKey + "suffix":        "session_key",
		"gl" + "rt-" + strings.Repeat("a", 20):      "gitlab_token",
		"AS" + "IA" + strings.Repeat("7", 16) + ".": "aws_access_key",
	} {
		if kind, ok := FindSecret(line, fixSecrets()); !ok || kind != want {
			t.Errorf("FindSecret(%q) = %q, %v, want %q", line, kind, ok, want)
		}
	}
	// An empty secret (the controller holds none) matches nothing.
	if kind, ok := FindSecret("anything at all", []Secret{NewSecret("session_key", "")}); ok {
		t.Errorf("an empty secret matched: %q", kind)
	}
}

// A refusal never repeats the secret, and a Secret cannot be printed, logged
// or marshalled by accident.
func TestSecretsDoNotLeak(t *testing.T) {
	b := fixWith(editEffect("pkg/example/sum.go", "a - b", "a + b // "+fakeSessionKey))
	_, err := PlanFix(b, goodEnvelope(t), goodBase(), fixSecrets())
	if err == nil || strings.Contains(err.Error(), fakeSessionKey) || strings.Contains(fmt.Sprintf("%+v", AsRefusal(err)), fakeSessionKey) {
		t.Fatalf("refusal leaks the secret (or is nil): %v", err)
	}
	s := NewSecret("session_key", fakeSessionKey)
	js, _ := json.Marshal(struct{ S Secret }{s})
	var logged bytes.Buffer
	slog.New(slog.NewJSONHandler(&logged, nil)).Info("x", "secret", s, "list", []Secret{s})
	for _, out := range []string{fmt.Sprintf("%v|%+v|%#v|%s", s, s, s, s), string(js), logged.String(), fmt.Sprint([]Secret{s})} {
		if strings.Contains(out, fakeSessionKey) {
			t.Errorf("a Secret printed its value: %s", out)
		}
	}
	if s.Name() != "session_key" {
		t.Errorf("Name = %q", s.Name())
	}
}

// Every refusal is typed, and its text starts with the rule code.
func TestRefusalIsTyped(t *testing.T) {
	_, err := PlanFix(fixWith(editEffect("pkg/example/other.go", "Other = 1", "Other = 2")), goodEnvelope(t), goodBase(), nil)
	r := AsRefusal(err)
	if r == nil || r.Rule != RuleCited || r.Effect != 0 || r.Path != "pkg/example/other.go" {
		t.Fatalf("refusal = %+v", r)
	}
	if RuleOf(err) != RuleCited || RuleOf(fmt.Errorf("wrapped: %w", err)) != RuleCited || RuleOf(nil) != "" || RuleOf(fmt.Errorf("plain")) != "" {
		t.Fatal("RuleOf does not see through wrapping, or invents a rule")
	}
	if !strings.HasPrefix(err.Error(), "effects: SC-CITED: effect 0 (pkg/example/other.go): ") {
		t.Fatalf("error text = %q", err)
	}
	// The codes are a closed, stable set: this list is the contract parts AGENT,
	// APPLY and the metrics key on. Changing it is a contract change.
	want := []Rule{"FX-SHAPE", "SC-FORM", "SC-PROT", "SC-CLASS", "SC-CITED", "SC-BEAD", "SC-SIZE", "SC-SECRET",
		"ED-MISSING", "ED-ENCODING", "ED-NOMATCH", "ED-AMBIGUOUS", "ED-EMPTIES", "ED-NOOP"}
	if !reflect.DeepEqual(Rules(), want) {
		t.Fatalf("Rules() = %v\nwant     %v", Rules(), want)
	}
}

// The envelope is plain controller data: nothing in it can be decoded from a
// batch, and PlanFix takes the lift and the cited files as ARGUMENTS.
func TestFixEnvelopeIsNotInTheBatch(t *testing.T) {
	for _, key := range []string{"cited", "lift", "secrets", "caps", "base", "envelope"} {
		doc := fmt.Sprintf(`{"verdict":"fix","effects":[{"kind":"edit","path":"a.go","old":"x","new":"y",%q:["a.go"]}]}`, key)
		if _, err := ParseBatch([]byte(doc)); err == nil {
			t.Errorf("ParseBatch accepted an edit carrying %q", key)
		}
	}
	// A diagnosis in the SAME batch cannot widen the cited bound: PlanFix reads
	// citations from the envelope only.
	b := fixWith(editEffect("pkg/example/other.go", "Other = 1", "Other = 2"))
	b.Effects = append(b.Effects, Effect{Kind: KindDiagnosis, Classification: ClassCode, Files: []string{"pkg/example/other.go"}})
	found := false
	for _, r := range FixViolations(b, goodEnvelope(t), goodBase(), nil) {
		found = found || r.Rule == RuleCited
	}
	if !found {
		t.Error("a diagnosis riding in the fix batch widened the cited-files bound")
	}
}
