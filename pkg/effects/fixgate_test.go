func fixSecrets() []Secret {
	return []Secret{NewSecret("session_key", fakeSessionKey), NewSecret("bot_pat", fakeBotPAT)}
}

func codes(rs []*Refusal) []string {
	out := []string{}
	for _, r := range rs {
		out = append(out, r.Code())
	}
	return out
}

func TestPlanFixAcceptsAGoodFix(t *testing.T) {
	env, base := goodEnvelope(t), goodBase()
	if v := FixViolations(goodFix(), env, base, fixSecrets()); len(v) != 0 {
		t.Fatalf("good fix has violations %v", codes(v))
	}
	plan, err := PlanFix(goodFix(), env, base, fixSecrets())
	if err != nil {
		t.Fatalf("PlanFix: %v", err)
	}
	wantContent := "package example\n\nfunc Sum(a, b int) int {\n\treturn a + b\n}\n"
	if plan.Verdict != VerdictFix || len(plan.Files) != 1 || plan.Files[0].Path != "pkg/example/sum.go" ||
		string(plan.Files[0].Content) != wantContent || !bytes.Equal(plan.Files[0].Base, base["pkg/example/sum.go"]) {
		t.Fatalf("plan files = %+v", plan.Files)
	}
	if plan.Reason != metaEffect().Reason || plan.Request != nil {
		t.Fatalf("plan rationale/request = %q / %+v", plan.Reason, plan.Request)
	}
	f := plan.Facts
	if f.FilesChanged != 1 || f.LinesAdded != 1 || f.LinesRemoved != 1 || f.NewBytes != len("\treturn a + b\n") || f.Edits != 1 {
		t.Fatalf("facts = %+v", f)
	}
	if f.Files[0].Class != scope.ClassSource || !reflect.DeepEqual(f.Classes(), []scope.Class{scope.ClassSource}) {
		t.Fatalf("facts classes = %v / %v", f.Files[0].Class, f.Classes())
	}
}

