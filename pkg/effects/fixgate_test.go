// The pre-apply fix gate (gonk-2usw plan 5.3, A1 and A4-A6): one fixture per
// predicate, each failing ONLY that predicate, asserted by RULE CODE.
//
// Everything here is invented (plan section 0): the package, the files, the
// "secrets" (assembled from fragments so no scanner mistakes them for one).

const fixBaseSHA = "0123456789abcdef0123456789abcdef01234567"

// packCaps are the plan 4.3 ceilings.
var packCaps = scope.Caps{MaxFiles: 3, MaxLines: 40, MaxDeletes: 0, MaxFileBytes: 256 << 10, MaxPatchBytes: 16 << 10}

func fold(t *testing.T, in scope.Input) scope.Effective {
	t.Helper()
	if in.BaseSHA == "" {
		in.BaseSHA = fixBaseSHA
	}
	eff, err := scope.Fold(in)
	if err != nil {
		t.Fatal(err)
	}
	return eff
}

func fixRow() scope.Row {
	return scope.Row{
		Classes:  []scope.Class{scope.ClassSource, scope.ClassTest, scope.ClassDocs},
		Liftable: []scope.Class{scope.ClassCI},
		Caps:     packCaps,
	}
}

var quiet = slog.New(slog.NewTextHandler(io.Discard, nil))

// goodEnvelope is the plan 4.2 `code` row: source and docs writable, no lift,
// the diagnosis's cited files as the bound.
func goodEnvelope(t *testing.T) FixEnvelope {
	t.Helper()
	eff := fold(t, scope.Input{Row: fixRow(), Enabled: true}).Narrow(scope.ClassSource, scope.ClassDocs)
	return FixEnvelope{
		Scope: eff,
		Cited: []string{
			"pkg/example/sum.go", "pkg/example/README.md", "pkg/example/sum_test.go",
			"pkg/example/a.go", "pkg/example/b.go", "pkg/example/c.go", "pkg/example/big.go",
			"pkg/example/zz_gen.go", "Makefile", ".gitlab-ci.yml",
		},
		Log: quiet,
	}
}

// ciEnvelope is the plan 4.2 `configuration` row: no ordinary class, the ci
// class through a lift the controller granted.
func ciEnvelope(t *testing.T) FixEnvelope {
	t.Helper()
	eff := fold(t, scope.Input{Row: fixRow(), Enabled: true, LiftOptIn: []scope.Class{scope.ClassCI}}).Narrow()
	lift, err := eff.GrantLift(scope.Grant{Trigger: "pipeline-fix", Workflow: "configuration", Classes: []scope.Class{scope.ClassCI}})
	if err != nil {
		t.Fatal(err)
	}
	env := goodEnvelope(t)
	env.Scope, env.Lift = eff, lift
	env.Cited = append(env.Cited, "ci/build.yml", ".gonk.yml", ".gitlab/deploy.key")
	return env
}

func numbered(n int, format string) string {
	var sb strings.Builder
	for i := 0; i < n; i++ {
		fmt.Fprintf(&sb, format+"\n", i)
	}
	return sb.String()
}

