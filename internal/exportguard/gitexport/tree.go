package gitexport

import (
	"os"
	"path"
	"path/filepath"
	"strings"

	"github.com/gonk-factory/gonk/internal/exportguard"
)

// RemovedEntry is how many files one internal-only entry removed.
type RemovedEntry struct {
	Entry string `json:"entry"`
	Files int    `json:"files"`
}

// TreeResult is the report of `tree`.
type TreeResult struct {
	Source        string         `json:"source_commit"`
	Version       string         `json:"version,omitempty"`
	Tree          string         `json:"tree"`
	ListSHA256    string         `json:"internal_only_sha256"`
	FilesInSource int            `json:"files_in_source"`
	FilesInTree   int            `json:"files_in_tree"`
	Removed       []RemovedEntry `json:"removed"`

	entries []treeEntry // of Tree
}

// Tree derives the public tree of src: the tree of src, minus the
// internal-only list AS IT IS AT src, plus one generated EXPORT-SOURCE file.
// version may be empty; when given it is recorded in EXPORT-SOURCE, so the
// tree id depends on it.
//
// The tree is written into the clone's object store and its id returned. It
// is a pure function of (src, version).
func (r *Repo) Tree(src, version string) (*TreeResult, error) {
	if err := r.resolveSource(src); err != nil {
		return nil, err
	}
	if version != "" && !exportguard.ValidVersion(version) {
		return nil, refuse("%q is not a vX.Y.Z version", version)
	}

	listBytes, ok, err := r.show(src, exportguard.ListPath)
	if err != nil {
		return nil, err
	}
	if !ok {
		return nil, refuse("%s does not exist at %s", exportguard.ListPath, src)
	}
	list, err := exportguard.ParseList(listBytes)
	if err != nil {
		return nil, refuse("%v", err)
	}

	srcEntries, err := r.lsTree(src)
	if err != nil {
		return nil, err
	}
	srcPaths := make([]string, len(srcEntries))
	for i, e := range srcEntries {
		srcPaths[i] = e.Path
		if e.Path == exportguard.ExportSourcePath || strings.HasPrefix(e.Path, exportguard.ExportSourcePath+"/") {
			return nil, refuse("%s already exists at %s; it is generated by the export and may not be committed", exportguard.ExportSourcePath, src)
		}
	}

	protected, err := r.protectedPaths(src, srcEntries)
	if err != nil {
		return nil, err
	}
	if err := list.CheckProtected(protected); err != nil {
		return nil, refuse("%v", err)
	}

	// The expected result, computed WITHOUT git: which paths stay.
	_, removed, err := list.Apply(srcPaths)
	if err != nil {
		return nil, refuse("%v", err)
	}

	// The tree itself, built with git in a private index.
	index := gitCmd{env: []string{"GIT_INDEX_FILE=" + r.tmp("index")}}
	if _, err := r.gitWith(index, "read-tree", src+"^{tree}"); err != nil {
		return nil, err
	}
	for _, entry := range list.Entries {
		if _, err := r.gitWith(index, "--literal-pathspecs", "rm", "--cached", "-r", "-q", "--", entry); err != nil {
			return nil, err
		}
	}

	content, err := exportguard.ExportSource{Version: version, SourceCommit: src, ListSHA256: list.SHA256}.Render()
	if err != nil {
		return nil, err
	}
	blob, err := r.gitWith(gitCmd{stdin: content}, "hash-object", "-w", "--stdin")
	if err != nil {
		return nil, err
	}
	if _, err := r.gitWith(index, "update-index", "--add", "--cacheinfo", "100644,"+blob+","+exportguard.ExportSourcePath); err != nil {
		return nil, err
	}
	tree, err := r.gitWith(index, "write-tree")
	if err != nil {
		return nil, err
	}

	entries, err := r.lsTree(tree)
	if err != nil {
		return nil, err
	}

	// The export's own data files, by blob id: they may not leave under any
	// name.
	dataBlobs := map[string]string{}
	for _, e := range srcEntries {
		if e.Path == exportguard.ListPath || e.Path == exportguard.DenyPath {
			dataBlobs[e.ID] = e.Path
		}
	}
	if err := checkPublicTree(list, srcEntries, entries, blob, dataBlobs); err != nil {
		return nil, err
	}

	res := &TreeResult{
		Source: src, Version: version, Tree: tree, ListSHA256: list.SHA256,
		FilesInSource: len(srcEntries), FilesInTree: len(entries), entries: entries,
	}
	for _, e := range list.Entries {
		res.Removed = append(res.Removed, RemovedEntry{Entry: e, Files: removed[e]})
	}
	return res, nil
}

// protectedPaths are the paths no internal-only entry may overlap: the
// hashed trees, and every build-context source an image Dockerfile copies.
func (r *Repo) protectedPaths(src string, entries []treeEntry) ([]string, error) {
	protected := append([]string{}, exportguard.HashedTrees...)
	isFile := map[string]bool{}
	for _, e := range entries {
		isFile[e.Path] = true
	}
	isDir := map[string]bool{}
	for _, e := range entries {
		for d := path.Dir(e.Path); d != "." && !isDir[d]; d = path.Dir(d) {
			isDir[d] = true
		}
	}
	for _, e := range entries {
		if !strings.HasPrefix(path.Base(e.Path), "Dockerfile") {
			continue
		}
		data, ok, err := r.show(src, e.Path)
		if err != nil {
			return nil, err
		}
		if !ok {
			continue
		}
		for _, s := range exportguard.DockerfileCopySources(data) {
			s = strings.TrimSuffix(path.Clean(s), "/")
			switch {
			case isFile[s]:
				protected = append(protected, s)
			case isDir[s]:
				protected = append(protected, s+"/")
			}
		}
	}
	return protected, nil
}

// checkPublicTree holds the definition of the public tree: it is the source
// tree minus the internal-only list plus EXPORT-SOURCE, and nothing else.
// tree is what git built (or what a mirror serves); the expectation is
// recomputed here from the source entries WITHOUT git. Every path, mode and
// blob must agree.
//
// dataBlobs maps the blob ids of the export's own data files to their paths:
// a file with one of those ids anywhere in the tree is a copy of the deny
// data under another name.
func checkPublicTree(list *exportguard.List, src, tree []treeEntry, exportSourceBlob string, dataBlobs map[string]string) error {
	want := map[string]treeEntry{
		exportguard.ExportSourcePath: {Mode: "100644", Type: "blob", ID: exportSourceBlob, Path: exportguard.ExportSourcePath},
	}
	for _, e := range src {
		if !list.Covers(e.Path) {
			want[e.Path] = e
		}
	}
	hasSource, hasData := false, false
	for _, e := range tree {
		if list.Covers(e.Path) {
			return refuse("internal-only path %s is present in the exported tree", e.Path)
		}
		if strings.HasPrefix(e.Path, exportguard.SelfDir) {
			hasData = true
		}
		if e.Path == exportguard.ExportSourcePath {
			hasSource = true
		}
		if p, ok := dataBlobs[e.ID]; ok {
			return refuse("%s is a copy of the export data file %s; the export data may not be published", e.Path, p)
		}
		if e.Type != "blob" {
			return refuse("%s is a %s, not a file; the exported tree may hold files only", e.Path, e.Type)
		}
	}
	if mode, err := exportguard.DetectMode(hasSource, hasData); err != nil {
		return refuse("the exported tree is not a public tree: %v", err)
	} else if mode != exportguard.ModePublic {
		return refuse("the exported tree has no %s", exportguard.ExportSourcePath)
	}
	if len(tree) != len(want) {
		return refuse("the exported tree has %d files, the recomputation expects %d", len(tree), len(want))
	}
	for _, e := range tree {
		if w, ok := want[e.Path]; !ok || w != e {
			return refuse("the exported tree differs from the recomputation at %s", e.Path)
		}
	}
	return nil
}

// WriteTree writes the files of a public tree into dir, which must be an
// absolute path that does not exist yet or is an empty directory. Nothing but
// the tree's files is written: no .git, no report.
//
// It then proves the directory IS the tree: the directory is hashed again
// with git, ignore rules off, and must give the tree id. `git archive` is not
// used anywhere -- it honours export-ignore attributes and would write less
// than the tree.
func (r *Repo) WriteTree(tr *TreeResult, dir string) error {
	if !filepath.IsAbs(dir) {
		return refuse("the directory to write the public tree into must be an absolute path, got %q", dir)
	}
	st, err := os.Stat(dir)
	switch {
	case err == nil && !st.IsDir():
		return refuse("%s is not a directory", dir)
	case err == nil:
		entries, err := os.ReadDir(dir)
		if err != nil {
			return err
		}
		if len(entries) != 0 {
			return refuse("%s is not empty; the public tree is written into an empty directory only", dir)
		}
	case os.IsNotExist(err):
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	default:
		return err
	}
	index := gitCmd{env: []string{"GIT_INDEX_FILE=" + r.tmp("index")}}
	if _, err := r.gitWith(index, "read-tree", tr.Tree); err != nil {
		return err
	}
	if _, err := r.gitWith(index, "checkout-index", "--all", "--prefix="+dir+string(filepath.Separator)); err != nil {
		return err
	}
	return r.verifyWritten(dir, tr.Tree)
}

// verifyWritten hashes a directory as a tree (every file, ignore rules off)
// into the clone's object store and requires the id to be tree.
func (r *Repo) verifyWritten(dir, tree string) error {
	gitDir, err := r.git("rev-parse", "--absolute-git-dir")
	if err != nil {
		return err
	}
	env := r.isolatedEnv("GIT_DIR="+gitDir, "GIT_WORK_TREE="+dir, "GIT_INDEX_FILE="+r.tmp("index"))
	if _, err := run(dir, env, nil, "add", "--all", "--force"); err != nil {
		return err
	}
	out, err := run(dir, env, nil, "write-tree")
	if err != nil {
		return err
	}
	if got := strings.TrimSpace(string(out)); got != tree {
		return refuse("the directory %s hashes to %s, not the public tree %s", dir, got, tree)
	}
	return nil
}
